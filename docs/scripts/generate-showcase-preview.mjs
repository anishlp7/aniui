#!/usr/bin/env node
/**
 * Regenerates docs/components/preview/showcase-preview.tsx from preview/*.tsx files.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const previewDir = path.join(__dirname, "../components/preview");
const outFile = path.join(previewDir, "showcase-preview.tsx");

const exportOverrides = {
  autocomplete: "PreviewAutoComplete",
  "carousel-3d": "PreviewCarousel3D",
  fab: "PreviewFAB",
  "input-otp": "PreviewInputOTP",
};

function slugToExport(slug) {
  return (
    "Preview" +
    slug
      .split("-")
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join("")
  );
}

function hasExport(content, name) {
  return new RegExp(`export function ${name}\\b`).test(content) || new RegExp(`export const ${name}\\b`).test(content);
}

function resolveExportName(slug, content) {
  if (exportOverrides[slug]) return exportOverrides[slug];

  const pascal = slugToExport(slug);
  if (hasExport(content, pascal)) return pascal;

  const defaultExport = `${pascal}Default`;
  if (hasExport(content, defaultExport)) return defaultExport;

  const match = content.match(/export function (Preview\w+)/);
  if (match) return match[1];

  throw new Error(`No preview export found for ${slug}`);
}

const slugs = fs
  .readdirSync(previewDir)
  .filter((f) => f.endsWith(".tsx") && f !== "showcase-preview.tsx")
  .map((f) => f.replace(".tsx", ""))
  .sort();

const exportNames = new Map();
for (const slug of slugs) {
  const content = fs.readFileSync(path.join(previewDir, `${slug}.tsx`), "utf8");
  exportNames.set(slug, resolveExportName(slug, content));
}

const imports = slugs
  .map((slug) => `import { ${exportNames.get(slug)} } from "@/components/preview/${slug}";`)
  .join("\n");

const mapEntries = slugs
  .map((slug) => {
    const key = slug.includes("-") ? `"${slug}"` : slug;
    return `  ${key}: ${exportNames.get(slug)},`;
  })
  .join("\n");

const content = `"use client";

/** Auto-generated by docs/scripts/generate-showcase-preview.mjs — do not edit manually. */
import React from "react";
${imports}

const previewMap = {
${mapEntries}
} as unknown as Record<string, React.ComponentType<{ className?: string }>>;

export function ShowcasePreview({ slug, className }: { slug: string; className?: string }) {
  const Preview = previewMap[slug];
  if (!Preview) {
    return (
      <div className={className}>
        <p className="text-xs text-muted-foreground text-center px-4">Preview unavailable</p>
      </div>
    );
  }
  return <Preview className={className} />;
}

export { previewMap };
`;

fs.writeFileSync(outFile, content);
console.log(`Generated ${outFile} with ${slugs.length} previews.`);
